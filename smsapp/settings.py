def _cast(kind, raw):
    if kind == "bool":
        return raw in ("1", "true", "True", 1, True)
    if kind == "int":
        return int(float(raw))
    if kind == "float":
        return float(raw)
    return raw


def all_values() -> dict:
    cache = g.get("_settings")
    if cache is None:
        stored = {r["key"]: r["value"] for r in rows("SELECT key, value FROM school_settings")}
        cache = {}
        for key, (kind, default, *_rest) in DEFS.items():
            try:
                cache[key] = _cast(kind, stored.get(key, default))
            except (TypeError, ValueError):
                cache[key] = _cast(kind, default)
        g._settings = cache
    return cache


def get(key):
    return all_values()[key]


def describe() -> list[dict]:
    vals = all_values()
    return [
        {"key": k, "type": t, "label": label, "group": grp, "help": hlp, "value": vals[k]}
        for k, (t, _d, label, grp, hlp) in DEFS.items()
    ]


def validate(key, value):
    from zoneinfo import ZoneInfo
    import re

    if key not in DEFS:
        raise ApiError(422, f"Unknown setting '{key}'.")
    kind = DEFS[key][0]
    label = DEFS[key][2]
    if kind == "bool":
        return "1" if value in (True, 1, "1", "true", "True") else "0"
    if kind in ("int", "float"):
        try:
            n = float(value)
        except (TypeError, ValueError):
            raise ApiError(422, f"{label} must be a number.", fields={key: "Must be a number."})
        if n < 0 or n > 100000:
            raise ApiError(422, f"{label} is out of range.", fields={key: "Out of range."})
        if key.endswith("threshold") and n > 100:
            raise ApiError(422, f"{label} must be between 0 and 100.", fields={key: "Must be 0-100."})
        return str(int(n)) if kind == "int" else str(round(n, 2))
    value = str(value if value is not None else "").strip()
    if len(value) > 300:
        raise ApiError(422, f"{label} is too long.", fields={key: "Too long."})
    if kind == "time":
        if not re.fullmatch(r"([01]\d|2[0-3]):[0-5]\d", value):
            raise ApiError(422, f"{label} must be a time like 10:00.", fields={key: "Use HH:MM."})
    if key == "timezone":
        try:
            ZoneInfo(value)
        except Exception:
            raise ApiError(422, "Unknown time zone.", fields={key: "Unknown time zone."})
    if key == "school_days":
        parts = [p.strip() for p in value.split(",") if p.strip()]
        if not parts or any(not p.isdigit() or not 1 <= int(p) <= 7 for p in parts):
            raise ApiError(422, "School days must be numbers 1-7 separated by commas.", fields={key: "Use numbers 1-7."})
        value = ",".join(sorted(set(parts)))
    if key == "school_name" and not value:
        raise ApiError(422, "School name is required.", fields={key: "Required."})
    return value


def save(changes: dict, user_id: int | None) -> dict:
    """Validate and store changed settings. Returns {key: (old, new)} for the audit log."""
    clean = {k: validate(k, v) for k, v in changes.items()}
    before = all_values()
    diff = {}
    with tx():
        for key, value in clean.items():
            execute(
                "INSERT INTO school_settings(key, value, updated_at, updated_by) VALUES (?,?,?,?) "
                "ON CONFLICT(key) DO UPDATE SET value=excluded.value, updated_at=excluded.updated_at, updated_by=excluded.updated_by",
                (key, value, utcnow_iso(), user_id),
            )
            new = _cast(DEFS[key][0], value)
            if before[key] != new:
                diff[key] = (before[key], new)
    g.pop("_settings", None)
    return diff


def put_raw(key, value):
    """Store a setting without validation (internal use, e.g. logo path)."""
    with tx():
        execute(
            "INSERT INTO school_settings(key, value, updated_at) VALUES (?,?,?) "
            "ON CONFLICT(key) DO UPDATE SET value=excluded.value, updated_at=excluded.updated_at",
            (key, value, utcnow_iso()),
        )
    g.pop("_settings", None)


